import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('screenshots', { recursive: true });
const baseURL = process.env.LAMB_BASE_URL || 'http://127.0.0.1:5173';
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true,chromiumSandbox:true});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',e=>errors.push(e.message));
await page.goto(baseURL);
await page.getByRole('button',{name:'Let’s cause trouble'}).waitFor();
await page.screenshot({path:'screenshots/desktop.png'});
await page.getByRole('button',{name:'Let’s cause trouble'}).click();
await page.keyboard.down('ArrowUp');
await page.waitForFunction(()=>window.__lamb.y<760 && window.__lamb.score>=1,null,{timeout:10000});
await page.keyboard.up('ArrowUp');
let state=await page.evaluate(()=>window.__lamb);assert.ok(state.y<760,'Keyboard moves the lamb');assert.ok(state.score>=1,'Collects flowers');
await page.getByRole('button',{name:'Pause game'}).click();
const paused=await page.evaluate(()=>window.__lamb);await page.waitForTimeout(350);
assert.equal((await page.evaluate(()=>window.__lamb)).time,paused.time,'Pause freezes time');
await page.getByRole('button',{name:'Back to mischief'}).click();
await page.waitForTimeout(500);await page.screenshot({path:'screenshots/gameplay-desktop.png'});
await page.getByRole('button',{name:'Pause game'}).click();await page.getByRole('button',{name:'Call it an afternoon'}).click();
await page.getByRole('button',{name:'Back to the meadow',exact:true}).click();
assert.ok(await page.getByText('PERSONAL BEST').count());
await page.getByRole('button',{name:'How to play'}).click();await page.getByRole('dialog').waitFor();await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Settings',exact:true}).click();await page.getByRole('button',{name:/Less motion/}).click();await page.getByRole('button',{name:'Lovely. Thank you.'}).click();
await page.reload();await page.getByRole('button',{name:'Let’s cause trouble'}).waitFor();
assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('lamb-on-the-lam:v1')).reducedMotion),true);
// Repeat actual round creation and teardown: no page reload between rounds.
for(let i=0;i<20;i++){
 await page.getByRole('button',{name:'Just a gentle stroll'}).click();
 await page.getByRole('button',{name:'Pause game'}).click();
 await page.getByRole('button',{name:'Call it an afternoon'}).click();
 await page.getByRole('button',{name:'Back to the meadow',exact:true}).click();
}
assert.equal(await page.locator('canvas').count(),1);
const phone=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,deviceScaleFactor:2});
phone.on('pageerror',e=>errors.push(e.message));
await phone.goto(baseURL);await phone.getByRole('button',{name:'Let’s cause trouble'}).waitFor();
await phone.screenshot({path:'screenshots/mobile.png'});
await phone.getByRole('button',{name:'Let’s cause trouble'}).click();
const cdp=await phone.context().newCDPSession(phone);
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:130,y:650}]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:130,y:590}]});
await phone.waitForTimeout(600);
await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
await phone.waitForTimeout(400);
const stopped=await phone.evaluate(()=>window.__lamb);assert.ok(stopped.y<800,'Touch moves the lamb');
await phone.waitForTimeout(250);assert.ok(Math.abs((await phone.evaluate(()=>window.__lamb)).y-stopped.y)<2,'Touch cancellation stops movement');
await phone.waitForTimeout(500);await phone.screenshot({path:'screenshots/gameplay-mobile.png'});
await phone.getByRole('button',{name:'Pause game'}).click();
await phone.setViewportSize({width:844,height:390});await phone.waitForTimeout(250);
assert.equal((await phone.evaluate(()=>window.__lamb)).phase,'paused');
await phone.getByRole('button',{name:'Back to mischief'}).click();await phone.waitForTimeout(200);
await phone.screenshot({path:'screenshots/landscape.png'});
await phone.getByRole('button',{name:'Pause game'}).click();await phone.getByRole('button',{name:'Call it an afternoon'}).click();
await phone.screenshot({path:'screenshots/results.png'});
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: keyboard movement, flower collection, pause/resume, help, settings persistence, 20 restarts, touch movement/cancellation, landscape resize, results, no browser errors.');
